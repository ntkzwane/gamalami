// Helper functions for cultural content
export function getCulturalContentByLanguage(language: string): CulturalContent[] {
  return culturalContent.filter(content => 
    content.language === language || content.language === 'all'
  );
}

export function getCulturalContentByType(type: string): CulturalContent[] {
  return culturalContent.filter(content => content.type === type);
}

export function getCulturalContentByWord(word: string): CulturalContent[] {
  return culturalContent.filter(content => 
    content.relatedWords.some(relatedWord => 
      relatedWord.toLowerCase().includes(word.toLowerCase())
    )
  );
}

export function getRandomCulturalContent(): CulturalContent {
  const randomIndex = Math.floor(Math.random() * culturalContent.length);
  return culturalContent[randomIndex];
}

export function searchCulturalContent(query: string): CulturalContent[] {
  const lowercaseQuery = query.toLowerCase();
  return culturalContent.filter(content => 
    content.title.toLowerCase().includes(lowercaseQuery) ||
    content.content.toLowerCase().includes(lowercaseQuery) ||
    content.relatedWords.some(word => word.toLowerCase().includes(lowercaseQuery))
  );
}